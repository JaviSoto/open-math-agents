"""Certify mixed A245212 families 2^a p^b q^c with arbitrary prime q>p.

Split intervals in a,b,c,q. Rational endpoint products bound the normalized
divisor sums. A missing upper endpoint is the exact infinite endpoint.
"""
from fractions import Fraction as F
from functools import lru_cache
from itertools import product
from math import prod, isqrt
from smooth_boxes_245212 import local


def runs(p):
    nodes = 0
    maxima = [0]*4

    @lru_cache(None)
    def moving(q,e):
        if q is None:
            return (F(1), F(0) if e is None else F(1,e+1))
        return local(q,e)

    def corners(xs):
        a,b,c,q=xs
        v=(local(2,a),local(p,b),moving(q,c))
        return prod(x for x,_ in v), prod(y for _,y in v)

    @lru_cache(None)
    def yband(q,e):
        if q is None:
            v=F(0) if e is None else F(1,e+1)
            return v,v
        if e is None:
            return F(0),F(0)
        if e<32:
            return local(q,e)[1],local(q,e)[1]
        y=F(q,(q-1)*(e+1))
        return y*(1-F(1,q**32)),y

    def evaluate(box):
        nonlocal nodes
        nodes+=1
        end=[(lo,) if hi==lo else (lo,hi) for lo,hi in box]
        lo=tuple(b[0] for b in box);hi=tuple(b[1] for b in box)
        xx=[]; yy=[]
        for i,(ql,qh) in enumerate([(2,2),(p,p),(lo[3],hi[3])]):
            yl=yband(qh,hi[i])[0]; yh=yband(ql,lo[i])[1]
            xl=1+(1-yh)/(qh-1) if qh is not None else F(1)
            xh=1+(1-yl)/(ql-1)
            xx.append((xl,xh)); yy.append((yl,yh))
        lx=prod(x[0] for x in xx); hx=prod(x[1] for x in xx)
        ly=prod(y[0] for y in yy); hy=prod(y[1] for y in yy)
        if lx+ly>2 or hx+hy<2:
            return None
        if lo[3]==hi[3] and any(lo[3]%h==0 for h in range(2,isqrt(lo[3])+1)):
            return None
        scores=[]
        for i,(low,high) in enumerate(box):
            if low==high:continue
            # Separate contributions: raw score can be stationary even when
            # both one-sided endpoint bounds vary.
            variation=0
            for v in product(*end):
                if v[i]!=low:continue
                w=v[:i]+(high,)+v[i+1:]
                xy=corners(v); zz=corners(w)
                variation=max(variation,abs(xy[0]-zz[0])+abs(xy[1]-zz[1]))
            scores.append((variation,i))
        if not scores:
            raise ValueError(f"equality at p={p}, (a,b,c,q)={lo}")
        _,j=max(scores);l,h=box[j]
        m=2*l+1 if h is None else max(l,min(h-1,2*(l+1)*(h+1)//(l+h+2)-1))
        maxima[j]=max(maxima[j],m+1)
        left=evaluate(box[:j]+((l,m),)+box[j+1:])
        right=evaluate(box[:j]+((m+1,h),)+box[j+1:])
        return j,m,left,right

    tree=evaluate(((1,None),(1,None),(1,None),(p+1,None)))
    return nodes,maxima,tree


def lean_table(tree):
    """Emit small kernel checks; every unchecked split is proved by bisect."""
    print("import MovingTree245212\n")
    print("/-! Generated by mixed_three_245212.py 3 --lean. -/")
    print("namespace OMA.Moving245212")
    print("open OMA.Smooth245212")
    print("set_option maxRecDepth 100000")
    print("set_option maxHeartbeats 10000000")
    print("def domain : Box := ![⟨1,none⟩,⟨1,none⟩,⟨1,none⟩,⟨4,none⟩]")
    def fmt(t):
        if t is None:
            return ".leaf"
        i,m,l,r=t
        return f"(.split {i} {m} {fmt(l)} {fmt(r)})"
    def walk(t,path,box):
        name="domain_excluded" if not path else "c"+path
        tree_str=fmt(t)
        if tree_str.count(".split")<=65:
            print(f"private def t{path} : Tree := {tree_str}")
            print(f"private theorem {name} : Excluded {box} := fun _ h => reject t{path} (by decide +kernel) h")
        else:
            i,m,l,r=t
            for d,child,action in [("l",l,"left"),("r",r,"right")]:
                print(f"private def b{path}{d} : Box := {action} {box} {i} {m}")
                walk(child,path+d,"b"+path+d)
            prefix='' if not path else 'private '
            print(f"{prefix}theorem {name} : Excluded {box} := bisect {box} {i} {m} c{path}l c{path}r")
    walk(tree,"","domain")
    print("end OMA.Moving245212")


if __name__=="__main__":
    import argparse
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("p",type=int)
    parser.add_argument("--lean",action="store_true")
    args=parser.parse_args()
    size,limits,proof=runs(args.p)
    if args.lean:
        if args.p != 3:
            parser.error("the Lean theorem uses the support 2,3,q")
        lean_table(proof)
    else:
        print(size,limits)
