"""Prove fixed-support A245212 exclusions using exact rational endpoint bounds.

Run python3 smooth_boxes_245212.py 2 3 5 7. An exponent with no upper bound
has the exact limiting local factors, so the root covers all positive exponents.
"""
from fractions import Fraction
from functools import lru_cache
from itertools import product
from math import isqrt, prod
import argparse


@lru_cache(None)
def local(p, e):
    if e is None:
        return Fraction(p, p - 1), Fraction(0)
    top = p**e
    t = (e + 1) * top
    s = (p * top - 1) // (p - 1)
    a = ((e + 1) * p * top - s) // (p - 1)
    return Fraction(a, t), Fraction(s, t)


def certify(primes, rectangular=False, lean=False):
    @lru_cache(None)
    def value(exponents):
        vals = [local(p, e) for p, e in zip(primes, exponents)]
        return prod(x for x, _ in vals) + prod(y for _, y in vals) - 2

    nodes = 0
    max_exponent = 0
    def rec(box):
        nonlocal nodes, max_exponent
        nodes += 1
        ends = [(lo,) if lo == hi else (lo,hi) for lo,hi in box]
        corners = [(xs, value(xs)) for xs in product(*ends)]
        true_corners = [v for xs,v in corners if None not in xs]
        if rectangular:
            lower = prod(local(p,lo)[0] for p,(lo,hi) in zip(primes,box))
            lower += prod(local(p,hi)[1] for p,(lo,hi) in zip(primes,box))
            upper = prod(local(p,hi)[0] for p,(lo,hi) in zip(primes,box))
            upper += prod(local(p,lo)[1] for p,(lo,hi) in zip(primes,box))
            if lower > 2 or upper < 2:
                return ".leaf"
        else:
            if min(v for xs,v in corners) >= 0 and min(true_corners) > 0:
                return ".leaf"
            if max(v for xs,v in corners) <= 0 and max(true_corners) < 0:
                return ".leaf"
        for xs,v in corners:
            if v==0 and None not in xs:
                raise ValueError(f"exact equality at {primes=} {xs=}")
        scores = []
        for j,(lo,hi) in enumerate(box):
            if lo == hi:
                continue
            variation = max(abs(v - value(xs[:j]+(hi,)+xs[j+1:]))
                            for xs,v in corners if xs[j]==lo)
            scores.append((variation,j))
        _, j = max(scores)
        lo,hi = box[j]
        # Bisect the interval in the coordinate 1/(e+1), closer to the
        # spacing of the local factors than the raw exponent coordinate.
        if hi is None:
            mid = 2*lo+1
        else:
            mid = max(lo, min(hi-1, 2*(lo+1)*(hi+1)//(lo+hi+2)-1))
        max_exponent = max(max_exponent,mid+1)
        l = rec(box[:j]+((lo,mid),)+box[j+1:])
        r = rec(box[:j]+((mid+1,hi),)+box[j+1:])
        if lean:
            return f"(.split {(2,3,5,7).index(primes[j])} {mid} {l} {r})"

    tree = rec(tuple((1,None) for p in primes))
    if lean:
        return tree
    return nodes, max_exponent, value.cache_info().currsize


def lean_tables():
    from itertools import combinations
    lines = ["import Smooth245212", "", "/-! Rational interval certificates generated by smooth_boxes_245212.py. -/",
             "namespace OMA.Smooth245212",
             "set_option maxRecDepth 100000", "set_option maxHeartbeats 10000000"]
    for j in range(1,4):
        for odd in combinations((3,5,7),j):
            ps = (2,)+odd
            name = "".join(map(str,ps))
            b = "!["+",".join("⟨1,none⟩" if p in ps else "⟨0,some 0⟩" for p in (2,3,5,7))+"]"
            tree = certify(ps,rectangular=True,lean=True)
            lines.extend([f"def box{name} : Box := {b}",
                          f"private def tree{name} : Tree := {tree}",
                          f"theorem reject{name} {{e : I → ℕ}} (h : ∀ i,(box{name} i).Contains (e i)) : score e ≠ 2 :=",
                          f"  tree{name}.sound (by decide +kernel) h",""])
    lines.extend(["end OMA.Smooth245212",""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("primes", nargs="*", type=int)
    parser.add_argument("--lean-tables", action="store_true", help="emit the seven mixed proof trees")
    args = parser.parse_args()
    if args.lean_tables:
        print(lean_tables())
        raise SystemExit(0)
    if not args.primes or len(set(args.primes)) != len(args.primes) or any(
            p < 2 or any(p % d == 0 for d in range(2, isqrt(p)+1))
            for p in args.primes):
        parser.error("inputs must be distinct primes")
    print(args.primes, certify(tuple(args.primes)))
