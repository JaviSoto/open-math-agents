"""Cover the odd A245212 family with all prime exponents equal.

Split prime-base and exponent intervals, allowing infinite upper endpoints.
Bounds on the normalized factors are rational. No search cutoff is taken
as a proof that an interval contains no solution.
"""
from fractions import Fraction as F
from functools import lru_cache
from math import prod, isqrt


@lru_cache(None)
def ybound(p, e):
    if e is None:
        return F(0), F(0)
    if p is None:
        return F(1,e+1), F(1,e+1)
    coarse = F(p,(p-1)*(e+1))
    if e<32:
        exact = coarse*(1-F(1,p**(e+1)))
        return exact,exact
    return coarse*(1-F(1,p**32)),coarse


def bounds(prime, exponent):
    p, P = prime
    e, E = exponent
    l,h = ybound(P,E)[0],ybound(p,e)[1]
    v = 1+(1-h)/(P-1) if P is not None else F(1)
    return v,1+(1-l)/(p-1),l,h


def split(l, h):
    return 2*l+1 if h is None else max(l,min(h-1,2*(l+1)*(h+1)//(l+h+2)-1))


def cover(k,budget=300000):
    assert 1<=k<=4
    nodes=0
    maxes=[0]*(k+1)
    def visit(box):
        nonlocal nodes
        nodes+=1
        if nodes>budget:
            raise ValueError("unresolved",box)
        e,*base=box
        for i,(p,P) in enumerate(base):
            if p==P and not all(p%v for v in range(2,isqrt(p)+1)):
                return None
            if i>0 and P is not None and P<=base[i-1][0]:
                return None
        vals=[bounds(b,e) for b in base]
        xl,xh,yl,yh=zip(*vals)
        if prod(xl)+prod(yl)>2 or prod(xh)+prod(yh)<2:
            return None
        gain=[]
        if e[0]!=e[1]:
            gain.append((sum((ybound(p,e[0])[1]-ybound(p,e[1])[0])*
                (F(1,p-1)*prod(xh[:i]+xh[i+1:])+prod(yh[:i]+yh[i+1:]))
                for i,(p,P) in enumerate(base)),0))
        for i,(p,P) in enumerate(base):
            if p==P:
                continue
            # Split to the next prime when a small integer interval is
            # separated eventually; the corresponding proofs still split
            # ordinary integer intervals consecutively.
            mag=(F(1,p-1)-(F(1,P-1) if P is not None else 0))*prod(xh[:i]+xh[i+1:])
            mag+=(ybound(p,e[0])[1]-ybound(P,e[0])[0])*prod(yh[:i]+yh[i+1:])
            gain.append((mag,i+1))
        if not gain:
            raise ValueError("singleton",box)
        _,i=max(gain)
        l,h=box[i]
        c=split(l,h)
        maxes[i]=max(maxes[i],c)
        return (i,c,visit(box[:i]+((l,c),)+box[i+1:]),
                visit(box[:i]+((c+1,h),)+box[i+1:]))
    initial=((1,None),(3,3))+tuple((p,None) for p in (5,7,11)[:k-1])
    tree=visit(initial)
    return tree,nodes,maxes


def lean(max_k):
    print("import EqualCover245212\n")
    print("/-! Equal-exponent interval certificates. Generated by equal_power_245212.py --lean. -/")
    print("namespace OMA.Equal245212")
    print("set_option maxHeartbeats 6000000\nset_option maxRecDepth 100000")
    def encode(t):
        if t is None:
            return ".leaf"
        i,c,l,r=t
        return f"(.split {i} {c} {encode(l)} {encode(r)})"
    def emit(k,t,path,box):
        expr=encode(t)
        symbol=f"h{k}{path}" if path else f"root{k}"
        if expr.count(".split")<=30:
            print(f"private def c{k}{path} : Cert {k} := {expr}")
            print(f"theorem {symbol} : Reject {box} := sound c{k}{path} (by decide +kernel)")
        else:
            i,c,l,r=t
            for direction,step,child in [("l","cutL",l),("r","cutR",r)]:
                name=f"b{k}{path}{direction}"
                print(f"private def {name} : Region {k} := {step} {box} {i} {c}")
                emit(k,child,path+direction,name)
            print(f"theorem {symbol} : Reject {box} := split {box} {i} {c} h{k}{path}l h{k}{path}r")
    for k in range(1,max_k+1):
        box="!["+ ",".join(["⟨1,none⟩","⟨3,some 3⟩"]+
            [f"⟨{p},none⟩" for p in (5,7,11)[:k-1]])+"]"
        print(f"def domain{k} : Region {k} := {box}")
        emit(k,cover(k)[0],"",f"domain{k}")
    print("end OMA.Equal245212")


if __name__=="__main__":
    import argparse
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lean",action="store_true")
    ap.add_argument("--max-rank",type=int,choices=range(1,5),default=4)
    args=ap.parse_args()
    if args.lean:
        lean(args.max_rank)
    else:
        for j in range(1,args.max_rank+1):
            _,nodes,limits=cover(j)
            print(j,nodes,limits,flush=True)
